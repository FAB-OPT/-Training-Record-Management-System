-- ════════════════════════════════════════════════════════════════════
-- เพิ่มคอลัมน์ companies ในตาราง quiz_meta
--
-- ใช้เก็บรายชื่อบริษัทในเครือ สำหรับเลือกตอนออกใบรายชื่อผู้เข้าอบรม
-- เดิมชื่อบริษัทฝังตายอยู่ในโค้ด (บริษัท เอฟเอบี ฟู้ดโฮลดิ้ง จำกัด)
-- ออกใบให้บริษัทอื่นในเครือไม่ได้เลย ต้องแก้โค้ดทุกครั้ง
--
-- เก็บเป็น array ของชื่อบริษัท เช่น
--   ["บริษัท เคที เรสทัวรองท์ จำกัด", "บริษัท โนมิมาโช จำกัด", ...]
--
-- ใช้ quiz_meta เพราะเป็นแถวเดียวที่ระบบโหลดอยู่แล้วทุกครั้ง
-- (ตารางนี้ทำหน้าที่เป็น "ค่าตั้งระบบ" ไปแล้วโดยปริยาย ไม่ได้มีแค่เรื่องข้อสอบ)
--
-- วิธีใช้: Supabase → โปรเจกต์ cyjfgperenakjeazsfgf → SQL Editor
--          วางทั้งไฟล์นี้แล้วกด Run (รันซ้ำได้ ไม่พัง)
-- ════════════════════════════════════════════════════════════════════

alter table public.quiz_meta
  add column if not exists companies jsonb not null default '[]'::jsonb;

-- แบบร่างใบรายชื่อต้องจำได้ด้วยว่าเลือกบริษัทไหนไว้
-- ไม่งั้นเปิดร่างเก่ามาทำต่อ จะเด้งกลับไปเป็นบริษัทเริ่มต้นเสมอ
alter table public.training_drafts
  add column if not exists company text;
