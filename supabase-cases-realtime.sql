-- เปิด Realtime ให้ตาราง cases
--
-- ผลลัพธ์: สาขากดแจ้งเคส → แอดมินเด้งขึ้นทันที
--          แอดมินอัปสถานะหรือลบ → หน้าสาขาอัปเดตให้เอง ไม่ต้องกดรีเฟรช
--          (ทำงานได้แม้ผู้ใช้ไม่ได้เปิดหน้าเคสค้างไว้ ขอแค่ยังล็อกอินอยู่)
--
-- วิธีใช้: Supabase → SQL Editor → วางแล้วกด Run (รันซ้ำได้ ไม่พัง)
-- ════════════════════════════════════════════════════════════════════

-- ให้ Realtime ส่งข้อมูลแถวเดิมมาด้วยตอน UPDATE/DELETE
-- ถ้าไม่ตั้ง จะได้แค่ id ตอนลบ ทำให้ฝั่งหน้าเว็บไม่รู้ว่าเป็นเคสของสาขาไหน
alter table public.cases replica identity full;

-- เพิ่มตารางเข้า publication ของ Realtime (ข้ามถ้าเพิ่มไปแล้ว)
do $$
begin
  alter publication supabase_realtime add table public.cases;
exception
  when duplicate_object then null;   -- เพิ่มไว้แล้ว ไม่ต้องทำอะไร
end $$;
