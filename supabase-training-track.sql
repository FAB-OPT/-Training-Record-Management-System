-- เพิ่มคอลัมน์ track ในตาราง trainings   ← ต้องรัน ระบบถึงจะบันทึกได้
--
-- อาการ: บันทึกการสอน Module 3 ครัว แล้วขึ้นว่า
--        "บันทึกขึ้นระบบไม่สำเร็จ — Could not find the 'track' column
--         of 'trainings' in the schema cache"
--
-- สาเหตุ: Module 3 ครัวต้องเลือกหน้างาน (สเต็ก / พาสต้า) ก่อนบันทึก
--        ค่านั้นถูกส่งไปในชื่อ track แต่ตารางบนฐานข้อมูลไม่มีคอลัมน์นี้
--        PostgREST ปฏิเสธทั้งแถว ไม่ใช่แค่ข้ามช่องที่ไม่รู้จัก
--        การสอนครั้งนั้นจึงไม่ได้ถูกบันทึกเลยแม้แต่ช่องเดียว
--
-- ที่ผ่านมาไม่มีใครรู้ เพราะโค้ดเดิมกลืน error ทิ้งเงียบ ๆ
-- ขึ้นข้อความว่าบันทึกสำเร็จตามปกติ แล้วข้อมูลหายตอนโหลดใหม่
-- เพิ่งมาเห็นตอนแก้ให้แจ้งเตือนเมื่อบันทึกไม่สำเร็จ
--
-- track เก็บอะไร:  'steak' = หน้างานสเต็ก · 'pasta' = หน้างานพาสต้า
--                 ว่าง = Module ที่ไม่ต้องเลือกหน้างาน (ส่วนใหญ่)
--
-- ใช้ตอนออกข้อสอบ — คนที่เรียนหน้างานสเต็กต้องได้ข้อสอบชุดสเต็ก
--
-- วิธีใช้: Supabase → โปรเจกต์ cyjfgperenakjeazsfgf → SQL Editor
--          วางทั้งไฟล์นี้แล้วกด Run (รันซ้ำได้ ไม่พัง)
-- ════════════════════════════════════════════════════════════════════

alter table public.trainings
  add column if not exists track text;

-- ค้นการสอนตามหน้างานได้เร็วขึ้น (ใช้ตอนดูว่าใครเรียนหน้างานไหนมาบ้าง)
create index if not exists trainings_track_idx
  on public.trainings (track);
