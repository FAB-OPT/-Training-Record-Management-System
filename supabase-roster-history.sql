-- เพิ่มคอลัมน์ issued_at ในตาราง training_drafts
--
-- ใช้แยกว่าเรคคอร์ดไหนคือ "แบบร่างที่ยังทำไม่เสร็จ" กับ "ใบที่ออก PDF ไปแล้ว"
--   issued_at ว่าง      = แบบร่าง แสดงในหน้าจัดอบรม
--   issued_at มีเวลา    = ออกใบไปแล้ว แสดงในเมนูใบรายชื่อที่ออกแล้ว
--
-- ปัญหาที่แก้: เดิมกดออกใบ PDF แล้วจบเลย ไม่มีบันทึกไว้ที่ไหน
--            อยากดูย้อนหลังว่าเคยจัดอบรมรุ่นไหนให้ใครบ้างก็ดูไม่ได้
--            ต้องไปรื้อไฟล์ PDF ที่พิมพ์เก็บไว้เอง
--
-- ใช้ตารางเดิมเพราะข้อมูลหน้าตาเหมือนกันทุกอย่าง (บริษัท หลักสูตร รุ่น
-- วันเวลา สถานที่ วิทยากร รายชื่อคน) ต่างกันแค่ออกใบแล้วหรือยัง
-- ไม่ต้องสร้างตารางใหม่และใช้โค้ดโหลด/บันทึกชุดเดิมได้เลย
--
-- วิธีใช้: Supabase → โปรเจกต์ cyjfgperenakjeazsfgf → SQL Editor
--          วางทั้งไฟล์นี้แล้วกด Run (รันซ้ำได้ ไม่พัง)
-- ════════════════════════════════════════════════════════════════════

alter table public.training_drafts
  add column if not exists issued_at text;

-- หน้าประวัติเรียงตามวันที่ออกใบล่าสุดก่อน
create index if not exists training_drafts_issued_idx
  on public.training_drafts (issued_at desc);
